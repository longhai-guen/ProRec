"""Tier 4, diagnostic 1 report (plan: docs/tier4-plan.md). Reads save/result/ablation.jsonl (latest record per key
wins) and the ProMax logs written with --log_sdr.

  1a  SDR weight statistics per epoch for ProMax full (is w stuck at its 0.1 floor?)
  1b  graph-train + SDR with sdr_tau x whiten x sdr_weight, seed 2025: validation and test Recall@20; picks the best
      (sdr_tau, whiten) by validation
  1c  best 1b (sdr_tau, whiten) x sdr_weight x sdr_w, seed 2025; picks the best by validation
  1d  best 1c setting with real / shuffled / random over seeds 2021-2025, against LightGCN+S2DR (s2dr-only)
The selections are written to save/result/tier4_best.json, which run_tier4.sh reads for the next stage.
Semantic gain = real - the content-free control with the higher mean, paired by seed; * = paired t-test p < 0.05.

Usage: python summarize_tier4.py [--k 20] [--out save/result/tier4_summary.md]
"""
import os
import re
import glob
import json
import argparse
from collections import defaultdict

import numpy as np

DATASETS = ['amazon', 'yelp', 'steam']
MODEL = 'lightgcn_promax'
SEL_SEED = 2025
GO_SEMANTIC = 0.002          # ADR 0001: semantic gain >= +0.002 Recall@20, p < 0.05, on >= 2 datasets
STAT_KEYS = ['w_mean', 'w_q25', 'w_q50', 'w_q75', 'w_floor', 'h_norm', 'sdr_loss']


def ttest_p(diffs):
    if len(diffs) < 2:
        return float('nan')
    try:
        from scipy.stats import ttest_1samp
    except ImportError:
        return float('nan')
    return float(ttest_1samp(diffs, 0.0).pvalue)


def ms(vals, signed=False):
    if not vals:
        return '-'
    fmt = '{:+.4f} ± {:.4f}' if signed else '{:.4f} ± {:.4f}'
    return fmt.format(np.mean(vals), np.std(vals, ddof=1) if len(vals) > 1 else 0.0)


def paired(a, b):
    """a, b: {seed: value}. Returns 'mean ± std* (w/n)' of a - b over shared seeds, the mean and the p-value."""
    seeds = sorted(set(a) & set(b))
    d = [a[s] - b[s] for s in seeds]
    if not d:
        return '-', float('nan'), float('nan')
    p = ttest_p(d)
    star = '*' if p < 0.05 else ''
    return '{}{} ({}/{})'.format(ms(d, signed=True), star, sum(x > 0 for x in d), len(d)), float(np.mean(d)), p


def table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    out += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(out)


def load_records(path, k):
    """rec[(dataset, variant_label, profile, score)][seed] = (test, val) at Recall@k; hp[label] = flags."""
    rec, hps = defaultdict(dict), {}
    with open(path) as f:
        for line in f:
            if not line.strip():
                continue
            r = json.loads(line)
            if r['model'] != MODEL or r.get('side', 'both') != 'both' or k not in r['k']:
                continue
            i = r['k'].index(k)
            val = r['val_recall'][i] if 'val_recall' in r else None
            label = r.get('variant', 'full')
            rec[(r['dataset'], label, r['profile'], r['score'])][r['seed']] = (r['recall'][i], val)
            if 'hp' in r:
                hps[label] = r['hp']
    return rec, hps


def sdr_log_stats(dataset):
    """Per-epoch SDR statistics from the newest ProMax full / real log of seed 2025 written with --log_sdr."""
    for path in sorted(glob.glob('save/log/{}/{}_seed{}_*.log'.format(MODEL, dataset, SEL_SEED)),
                       key=os.path.getmtime, reverse=True):
        epochs, best = [], None
        with open(path) as f:
            for line in f:
                m = re.search(r'\[Epoch\s+(\d+) /', line)
                if m and 'w_mean' in line:
                    vals = dict((k, float(v)) for k, v in re.findall(r'(\w+):+ (-?[\d.]+)', line))
                    epochs.append((int(m.group(1)), vals))
                m = re.search(r'Best Epoch (\d+)', line)
                if m:
                    best = int(m.group(1))
        if epochs:
            return path, epochs, best
    return None, [], None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--file', default='save/result/ablation.jsonl')
    parser.add_argument('--k', type=int, default=20)
    parser.add_argument('--out', default='save/result/tier4_summary.md')
    parser.add_argument('--best', default='save/result/tier4_best.json')
    args = parser.parse_args()
    rec, hps = load_records(args.file, args.k)
    best = {}
    if os.path.exists(args.best):
        with open(args.best) as f:
            best = json.load(f)
    R = 'Recall@{}'.format(args.k)
    md = ['# Tier 4, diagnostic 1: SDR scale', '',
          'Generated by `summarize_tier4.py`. Selection uses validation {} at seed {} only.'.format(R, SEL_SEED), '']

    # 1a: SDR weight statistics
    md += ['## 1a. SDR weight w = clamp(1 − H_norm, 0.1, 1) during ProMax training (full, real, seed 2025)', '',
           'Per-epoch means over batches. `w_floor` = share of users with w at the 0.1 floor.', '']
    rows = []
    for ds in DATASETS:
        path, epochs, best_ep = sdr_log_stats(ds)
        if not epochs:
            rows.append([ds, '-', 'no --log_sdr log yet'] + [''] * (len(STAT_KEYS) - 1))
            continue
        picks = [('first', epochs[0])]
        if best_ep is not None:
            near = min(epochs, key=lambda e: abs(e[0] - best_ep))
            picks.append(('best', near))
        picks.append(('last', epochs[-1]))
        for name, (ep, vals) in picks:
            rows.append([ds, '{} ({})'.format(name, ep)] + ['{:.4f}'.format(vals[k]) if k in vals else '-' for k in STAT_KEYS])
    md += [table(['dataset', 'epoch'] + STAT_KEYS, rows), '']

    def stage_rows(ds, labels):
        rows, scored = [], []
        for label in labels:
            v = rec.get((ds, label, 'real', 'model'), {}).get(SEL_SEED)
            if v is None:
                continue
            test, val = v
            rows.append([label, '{:.4f}'.format(val) if val is not None else '-', '{:.4f}'.format(test)])
            if val is not None and label in hps:
                scored.append((val, label))
        return rows, scored

    def baseline_row(ds):
        v = rec.get((ds, 's2dr-only', 'real', 'model'), {}).get(SEL_SEED)
        return [['s2dr-only (LightGCN+S2DR)', '{:.4f}'.format(v[1]) if v and v[1] is not None else '-',
                 '{:.4f}'.format(v[0]) if v else '-']]

    # 1b: target sharpness
    md += ['## 1b. Target temperature × profiles × SDR weight (graph-train + SDR, seed 2025)', '']
    best.setdefault('1b', {})
    for ds in DATASETS:
        labels = sorted(l for l, h in hps.items() if l.startswith('graph-train+') and set(h) == {'sdr_tau', 'whiten', 'sdr_weight'})
        rows, scored = stage_rows(ds, labels)
        if not rows:
            continue
        if scored:
            _, label = max(scored)
            best['1b'][ds] = {k: hps[label][k] for k in ('sdr_tau', 'whiten')}
            rows = [r + ['← best' if r[0] == label else ''] for r in rows]
        md += ['### ' + ds, '', table(['setting', 'val ' + R, 'test ' + R, ''], baseline_row(ds) + rows), '']

    # 1c: strength and weighting
    md += ['## 1c. SDR weight × per-user weighting (best 1b setting, seed 2025)', '']
    best.setdefault('1c', {})
    for ds in DATASETS:
        b = best['1b'].get(ds)
        if not b:
            continue
        labels = sorted(l for l, h in hps.items() if l.startswith('graph-train+') and len(h) == 4
                        and all(h[k] == b[k] for k in b))
        rows, scored = stage_rows(ds, labels)
        if not rows:
            continue
        if scored:
            _, label = max(scored)
            best['1c'][ds] = dict(hps[label])
            rows = [r + ['← best' if r[0] == label else ''] for r in rows]
        md += ['### ' + ds, '', table(['setting', 'val ' + R, 'test ' + R, ''], baseline_row(ds) + rows), '']

    # 1d: final, 5 seeds
    md += ['## 1d. Best setting over 5 seeds, against LightGCN+S2DR', '']
    rows, go = [], []
    for ds in DATASETS:
        b = best['1c'].get(ds)
        if not b:
            continue
        label = next((l for l, h in hps.items() if l.startswith('graph-train+') and h == b), None)
        if label is None:
            continue
        get = lambda prof, lab=label: {s: v[0] for s, v in rec.get((ds, lab, prof, 'model'), {}).items()}
        real, shuf, rand = get('real'), get('shuffled'), get('random')
        if not real:
            continue
        control_name, control = max((('shuffled', shuf), ('random', rand)),
                                    key=lambda c: np.mean(list(c[1].values())) if c[1] else -1)
        base = get('real', 's2dr-only')
        promax = get('real', 'full')
        sem, sem_mean, sem_p = paired(real, control)
        go.append(sem_mean >= GO_SEMANTIC and sem_p < 0.05)
        rows.append([ds, label, ms(list(real.values())), ms(list(control.values())) + ' ({})'.format(control_name),
                     sem, paired(real, base)[0], paired(real, promax)[0]])
    md += [table(['dataset', 'setting', 'real', 'best control', 'semantic gain', 'real − LightGCN+S2DR',
                  'real − ProMax'], rows), '']
    if go:
        n = sum(go)
        md += ['**Go signal (ADR 0001)**: semantic gain ≥ +{} {} with p < 0.05 on {} of {} datasets → {}.'.format(
            GO_SEMANTIC, R, n, len(go), 'met' if n >= 2 else 'not met'), '']

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        f.write('\n'.join(md) + '\n')
    with open(args.best, 'w') as f:
        json.dump(best, f, indent=2)
    print('\n'.join(md))
    print('Written to {} and {}'.format(args.out, args.best))


if __name__ == '__main__':
    main()
